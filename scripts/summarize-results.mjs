// Turns reports/differential.json + reports/historical.json into the web app's results.json
// and docs/RESULTS.md (gas table included).
import { readFileSync, writeFileSync } from "node:fs";

const d = JSON.parse(readFileSync("reports/differential.json", "utf8"));
const h = JSON.parse(readFileSync("reports/historical.json", "utf8"));
const gas = Object.entries(d.gas)
  .filter(([, v]) => v.original && v.reborn)
  .map(([op, v]) => {
    const o = Number(BigInt(v.original.total) / BigInt(v.original.n));
    const r = Number(BigInt(v.reborn.total) / BigInt(v.reborn.n));
    return { op, n: v.original.n, original: o, reborn: r, deltaPct: ((r - o) / o) * 100 };
  })
  .sort((a, b) => a.op.localeCompare(b.op));
const orig = h.results.find((r) => r.impl === "original");
const summary = {
  differential: {
    scenarios: d.scenarios, ops: d.ops, okOps: d.okOps, revertedOps: d.revertedOps,
    comparisons: d.comparisons, mismatches: d.mismatches.length, reasons: d.reasons, byKind: d.byKind,
  },
  historical: {
    cases: orig.cases, exact: Math.min(...h.results.map((r) => r.exact)), modelExact: orig.modelExact,
    routerExactOut: orig.routerExactOut, fromBlock: h.fromBlock, toBlock: h.toBlock,
  },
  gas,
};
writeFileSync("apps/web/lib/results.json", JSON.stringify(summary, null, 2) + "\n");

const rows = gas.map((g) => `| ${g.op} | ${g.n} | ${g.original.toLocaleString("en-US")} | ${g.reborn.toLocaleString("en-US")} | ${g.deltaPct > 0 ? "+" : ""}${g.deltaPct.toFixed(1)}% |`);
const reasons = Object.entries(d.reasons).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| \`${k}\` | ${v} |`);
const kinds = Object.entries(d.byKind).sort().map(([k, v]) => `| ${k} | ${v.total} | ${v.ok} | ${v.total - v.ok} |`);
const comps = Object.entries(d.comparisons).map(([k, v]) => `| ${k} | ${v} |`);
const md = `# Results

Generated by \`scripts/summarize-results.mjs\` from \`reports/differential.json\` and \`reports/historical.json\`.

## Differential fuzz

${d.scenarios} seeded scenarios x ${d.steps} ops = **${d.ops} ops**, each executed on the original mainnet bytecode, on the reborn Solidity, and on the TypeScript model (two model instances, one per deployment). **Mismatches: ${d.mismatches.length}.**

| comparison | count |
|---|---|
${comps.join("\n")}

Every comparison checks success or revert, the exact revert string, every emitted event (emitter, name, arguments, order), and after every op the full observable state (reserves, timestamps, both price accumulators, kLast, LP supply and balances, token and ETH balances).

| op | total | succeeded | reverted |
|---|---|---|---|
${kinds.join("\n")}

Revert reasons exercised (original bytecode, all matched):

| reason | count |
|---|---|
${reasons.join("\n")}

## Historical replay

${orig.cases} real swaps on the mainnet WETH/USDC pair, blocks ${h.fromBlock} to ${h.toBlock}. For each, the pre-swap reserves are rebuilt in a fresh pool, the recorded input is sent and \`swap\` is called with the recorded outputs. The resulting \`Sync\` must equal the one mainnet emitted.

| implementation | exact | model exact |
|---|---|---|
${h.results.map((r) => `| ${r.impl} | ${r.exact}/${r.cases} | ${r.modelExact}/${r.cases} |`).join("\n")}

${orig.routerExactOut} of ${orig.cases} real swaps took exactly the router's \`getAmountOut\` quote; the rest were aggregator or MEV swaps that asked for less, which the pair accepts as long as K holds.

## Gas

Mean execution gas per successful op from the same fuzz run (in-process EVM, Cancun rules, excludes the 21,000 intrinsic cost and calldata). The original is solc 0.5.16 (core) and 0.6.6 (router); reborn is solc 0.8.28 with optimizer runs 999999.

| op | samples | original | reborn | delta |
|---|---|---|---|---|
${rows.join("\n")}
`;
writeFileSync("docs/RESULTS.md", md);
console.log(md);
